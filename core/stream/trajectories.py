"""Continuous, bounded encounter geometry in proper kpc/km/s/Myr.

Hermite extrema and distance stationary points are solved as polynomials.
Saved-center minima are retained separately. Input interpolation certificates
are evidence supplied by a trajectory campaign, never generated by this code.
"""

